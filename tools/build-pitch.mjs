/* ── pitch accents for the deck ──

     node tools/build-pitch.mjs        # writes src/data/pitch.js from the local Kanjium cache

   Source: Kanjium accents.txt (mifunetoshiro/kanjium, CC BY-SA 4.0) — 124,137 words as
   "word <tab> reading <tab> accent[,accent]". Downloaded once to tools/.accents-cache.txt
   (git-ignored); only the accents for words actually in the deck are written out, so the
   app carries a few kilobytes, not the dictionary.

   A word is looked up by its written form AND its reading together — 端 alone is はし 0,
   はな 1, はじ 0 … and only the pair says which. Where Kanjium lists two accents, the
   first is the one given. A deck word Kanjium does not know is simply left without one:
   no mark is better than a wrong mark. */

import fs from "node:fs";
import { SEED } from "../src/data/seed.js";
import { cleanWord } from "./wordform.mjs";

const CACHE = new URL("./.accents-cache.txt", import.meta.url);
const OUT = new URL("../src/data/pitch.js", import.meta.url);

export const hira = (s) => String(s || "").replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));
/* The plain word a deck card stands for: conjugation notes, optional parts in brackets,
   leading 〜 and pitch arrows removed. */
export const plain = (s) => cleanWord(s).replace(/[（(][^）)]*[）)]/g, "").replace(/[〜~↓↑\s]/g, "").trim();

export function accentIndex(text) {
  const m = new Map();
  const byReading = new Map();             // reading -> Set of accents, across every spelling
  for (const line of String(text).split(/\r?\n/)) {
    const [w, r, a] = line.split("\t");
    if (!w || !r || !a) continue;
    const n = parseInt(a, 10);
    if (!Number.isInteger(n)) continue;
    const k = w + "|" + hira(r);
    if (!m.has(k)) m.set(k, n);
    if (w === r || hira(w) === hira(r)) { const kk = hira(w) + "|" + hira(r); if (!m.has(kk)) m.set(kk, n); }
    if (!byReading.has(hira(r))) byReading.set(hira(r), new Set());
    byReading.get(hira(r)).add(n);
  }
  /* A word written in kana (わかる) is filed under its kanji spelling (分かる), so the pair
     lookup misses it. Its reading alone is trusted only when every word with that reading
     has the same accent — はし (箸 1, 橋 2, 端 0) gets nothing, and should. */
  m.unique = (r) => { const s = byReading.get(hira(r)); return s && s.size === 1 ? [...s][0] : null; };
  return m;
}

export function accentFor(index, term, reading) {
  const t = plain(term), r = hira(plain(reading || term));
  if (!t || !r) return null;
  for (const k of [t + "|" + r, hira(t) + "|" + r, r + "|" + r]) if (index.has(k)) return index.get(k);
  if (/^[\u3040-\u30ffー]+$/.test(t) && index.unique) return index.unique(r);
  return null;
}

const invoked = process.argv[1] && process.argv[1].replace(/\\/g, "/").endsWith("tools/build-pitch.mjs");
if (invoked) {
  const index = accentIndex(fs.readFileSync(CACHE, "utf8"));
  const out = {};
  let hit = 0;
  for (const c of SEED) {
    const a = accentFor(index, c.term, c.reading);
    if (a === null) continue;
    out[plain(c.term) + "|" + hira(plain(c.reading || c.term))] = a;
    hit++;
  }
  const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join("\n");
  fs.writeFileSync(OUT, `/* Pitch accents for the deck's words, keyed "word|reading" (reading in hiragana).
   From Kanjium accents.txt (mifunetoshiro/kanjium), CC BY-SA 4.0. Generated by
   tools/build-pitch.mjs — do not edit by hand. */

export const PITCH = {
${body}
};
`);
  process.stderr.write(`pitch: ${hit} of ${SEED.length} deck words (${Object.keys(out).length} distinct)\n`);
}
