/* ── the Volume 2 textbook's own kanji order ──
   NihonGO NOW! Volume 2 teaches 133 numbered kanji across its reading scenes (7-8R …
   12-9R), each introduced as "日 #1." with readings and example words. The Kanji tab
   ordered characters by newspaper frequency and by how often they appear in the deck, so
   the textbook's sequence — the one Matthew is actually being taught and tested on — was
   nowhere in the app.

   This extracts the sequence only: number, character, scene. Nothing else from the book is
   kept, so the output can live in the repo (src/data/book-kanji.js). Meanings and readings
   still come from KANJIDIC (kanji.json); the words a kanji is practised in come from the
   deck.

     pdftotext -enc UTF-8 vol2-textbook.pdf vol2.txt
     node tools/extract-book-kanji.mjs vol2.txt [second-copy.txt] > src/data/book-kanji.js

   Two sources, cross-checked:
   - the character headers, which pdftotext renders in three layouts ("日 #1.",
     "#4. 来", "#28. 語 ゴ");
   - the practice instructions, "…kanji characters #34-43 for Scene 9-7", which give every
     number's scene as a range.
   A number with no header in either copy, or two different characters for one number,
   fails loudly rather than being guessed. */

import fs from "node:fs";

const KANJI = "[\\u4e00-\\u9fff々]";
const HEADERS = [
  new RegExp(`^(${KANJI}) ?#(\\d{1,3})\\.`),          // 日 #1.
  new RegExp(`^#(\\d{1,3})\\. ?(${KANJI})(?:\\s|$)`),  // #4. 来   /   #28. 語 ゴ
];

/* The third layout: "#56." or "#53. 1. 2. 3." alone, with the character a few lines down
   as the first thing on its own line ("山 やま サン", "短"). */
const BARE = /^#(\d{1,3})\.(?:\s+\d+\.)*\s*$/;
const LEAD = new RegExp(`^(${KANJI})(?:\\s|$)`);

export function headersIn(text) {
  const found = new Map();                 // n -> Set of characters
  const lines = String(text).split(/\r?\n/).map((l) => l.replace(/^\f/, "").trim());
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    let n = null, c = null, m;
    if ((m = line.match(HEADERS[0]))) { c = m[1]; n = +m[2]; }
    else if ((m = line.match(HEADERS[1]))) { n = +m[1]; c = m[2]; }
    else if ((m = line.match(BARE))) {
      for (let k = 1; k <= 6 && !c; k++) { const lm = (lines[i + k] || "").match(LEAD); if (lm) c = lm[1]; }
      if (c) n = +m[1];
    }
    if (n == null) continue;
    if (!found.has(n)) found.set(n, new Set());
    found.get(n).add(c);
  }
  return found;
}

/* "…characters #34-43 for Scene 9-7." / "# 59–67 for Scene 10-7." / "#5-8 for Scenes 7–9." */
export function scenesIn(text) {
  const out = new Map();                   // n -> "9-7R"
  const re = /kanji characters #? ?(\d{1,3}) ?[-–] ?(\d{1,3}) for Scenes? (\d{1,2})[-–](\d)/g;
  let m;
  while ((m = re.exec(String(text)))) {
    for (let n = +m[1]; n <= +m[2]; n++) out.set(n, `${m[3]}-${m[4]}R`);
  }
  return out;
}

export function bookKanji(texts) {
  const heads = new Map();
  for (const t of texts) for (const [n, set] of headersIn(t)) {
    if (!heads.has(n)) heads.set(n, new Set());
    for (const c of set) heads.get(n).add(c);
  }
  const scenes = scenesIn(texts[0]);
  const max = Math.max(...scenes.keys());
  const rows = [], problems = [];
  for (let n = 1; n <= max; n++) {
    const cs = heads.get(n) ? [...heads.get(n)] : [];
    if (cs.length !== 1) problems.push(`#${n}: ${cs.length ? "conflicting " + cs.join("/") : "no header found"}`);
    if (!scenes.has(n)) problems.push(`#${n}: no scene`);
    rows.push({ n, c: cs[0] || null, sec: scenes.get(n) || null });
  }
  const dup = rows.filter((r, i) => r.c && rows.findIndex((x) => x.c === r.c) !== i);
  for (const d of dup) problems.push(`#${d.n}: ${d.c} already numbered earlier`);
  return { rows, problems };
}

const invoked = process.argv[1] && process.argv[1].replace(/\\/g, "/").endsWith("tools/extract-book-kanji.mjs");
if (invoked) {
  const files = process.argv.slice(2);
  if (!files.length) { console.error("usage: node tools/extract-book-kanji.mjs vol2.txt [copy2.txt]"); process.exit(2); }
  const { rows, problems } = bookKanji(files.map((f) => fs.readFileSync(f, "utf8")));
  if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
  const body = rows.map((r) => `  [${r.n}, "${r.c}", "${r.sec}"],`).join("\n");
  process.stdout.write(`/* NihonGO NOW! Level 1 Volume 2: the 133 kanji in the order the textbook numbers and
   introduces them, with the reading scene that introduces each. Generated by
   tools/extract-book-kanji.mjs from the local textbook PDF; only number, character and
   scene are kept. Readings and meanings come from KANJIDIC (kanji.json), and the words a
   kanji is practised in come from the deck. */

// [number, character, scene]
export const BOOK_KANJI = [
${body}
];
`);
}
