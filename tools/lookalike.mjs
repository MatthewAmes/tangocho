/* ── kanji that look alike ──
   A learner who answers 持 (hold) for 待 (wait) has not forgotten a meaning — they have not
   SEEN the difference: both are 寺 with something on the left. Drilling either kanji
   harder does not fix that; being shown the one part that differs does.

   This module answers three questions from the KRADFILE breakdown in
   src/data/kanji-parts.js (generated by tools/build-kanji-parts.mjs):

     partsOf(c)            the parts a kanji is built from, with plain-English names
     lookalikesOf(c)       the kanji it is most easily mistaken for
     kanjiDiff(a, b)       what two kanji share and what tells them apart

   and two for the rest of the app: termLookalike(x, y) says whether two WORDS differ only
   by lookalike kanji (待つ / 持つ), and lookalikeScore ranks wrong answers for a question.

   It describes what is on the page and nothing else. Which part carries the sound, and the
   story of how a kanji came to be, are left out deliberately: popular etymologies are
   often wrong, and "the 彳 is a step and the 扌 is a hand" is all a learner needs to stop
   mixing up 待 and 持.

   Pure — see tools/test-lookalike.mjs. */
