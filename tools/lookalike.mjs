const split = (s) => (s ? String(s).split(" ").filter(Boolean) : []);
const part = (el) => ({ el, show: SHOW[el] || el, name: PART_NAMES[el] || "" });

/* The named parts of a kanji, for showing. Empty for a kanji that is a single part itself
   (土, 力): there is nothing to break down, and its lookalikes carry the lesson instead. */
export function partsOf(c) {
  return split(KANJI_PARTS[c]).map(part).filter((p) => p.name);
}

const curatedFor = new Map();
for (const { pair, note } of CURATED) {
  const [a, b] = [...pair];
  curatedFor.set(a + b, note); curatedFor.set(b + a, note);
}
export const curatedNote = (a, b) => curatedFor.get(a + b) || null;

/* The kanji `c` is most easily mistaken for, most alike first. `within` (a Set of kanji)
   keeps the list to kanji the learner actually meets: 読 looks like a dozen kanji, and the
   one that matters is the 続 in their own course. */
export function lookalikesOf(c, within = null) {
  const list = [...String(LOOKALIKES[c] || "")];
  return within ? list.filter((x) => within.has(x)) : list;
}

export function areLookalike(a, b) {
  if (!a || !b || a === b) return false;
  return !!curatedNote(a, b) || lookalikesOf(a).includes(b) || lookalikesOf(b).includes(a);
}

/* What two kanji share and what tells them apart. Compared on the top-level parts, and
   on the full element lists when those come out identical (they can: the difference is
   then a stroke, which only a hand-written note can describe). */
export function kanjiDiff(a, b) {
  if (!a || !b || a === b) return null;
  const pa = split(KANJI_PARTS[a]), pb = split(KANJI_PARTS[b]);
  const shared = pa.filter((x) => pb.includes(x));
  const named = (xs) => xs.map(part).filter((p) => p.name);
  return {
    a, b,
    shared: named(shared),
    onlyA: named(pa.filter((x) => !pb.includes(x))),
    onlyB: named(pb.filter((x) => !pa.includes(x))),
    note: curatedNote(a, b),
  };
}

const listParts = (ps) => ps.map((p) => `${p.show} (${p.name})`).join(" and ");

/* The difference as one sentence a learner can act on. `gloss` (optional) maps a kanji to
   a short meaning, so the sentence can say which is which. Null when the parts cannot say
   anything useful and no note was written — better silent than a vague sentence. */
export function diffSentence(diff, gloss = () => "") {
  if (!diff) return null;
  if (diff.note) return diff.note;
  const name = (c) => (gloss(c) ? `${c} (${gloss(c)})` : c);
  if (!diff.onlyA.length && !diff.onlyB.length) return null;
  const has = (c, ps) => (ps.length ? `${name(c)} has ${listParts(ps)}` : `${name(c)} has nothing more`);
  const both = diff.shared.length ? `Both have ${listParts(diff.shared)}. ` : "";
  return `${both}${has(diff.a, diff.onlyA)}; ${has(diff.b, diff.onlyB)}.`;
}

const KANJI = /[一-鿿々]/;
/* Two words that differ ONLY where a kanji was swapped for a lookalike: 待つ / 持つ,
   時間 / 時聞. Returns the first such pair, or null. */
export function termLookalike(x, y) {
  const A = [...String(x || "")], B = [...String(y || "")];
  if (!A.length || A.length !== B.length) return null;
  let first = null;
  for (let i = 0; i < A.length; i++) {
    if (A[i] === B[i]) continue;
    if (!KANJI.test(A[i]) || !KANJI.test(B[i]) || !areLookalike(A[i], B[i])) return null;
    if (!first) first = { a: A[i], b: B[i] };
  }
  return first;
}

/* How good a wrong answer `other` is for a question on `card`, 0 to 1, by shape alone.
   A single kanji is scored by its place in the lookalike list (a hand-written pair first);
   a word scores only if it differs from the card's word by lookalike kanji and nothing
   else. Everything else is 0 and falls through to the other distractor tiers. */
export function lookalikeScore(card, other) {
  const x = card && card.term, y = other && other.term;
  if (!x || !y || x === y) return 0;
  if ([...x].length === 1 && [...y].length === 1) {
    if (curatedNote(x, y)) return 1;
    const list = lookalikesOf(x);
    const i = list.indexOf(y);
    if (i >= 0) return 0.9 - (0.4 * i) / Math.max(1, list.length);
    return lookalikesOf(y).includes(x) ? 0.5 : 0;
  }
  return termLookalike(x, y) ? 0.8 : 0;
}

export const hasBreakdown = (c) => !!KANJI_ELEMENTS[c];

/* The one line to show after a mix-up between two cards, or null when the mix-up was not
   about shape. Two single kanji that are lookalikes, or two words that differ only by
   lookalike kanji, get the difference spelled out; anything else gets nothing here. */
export function lookalikeLine(a, b, gloss = () => "") {
  const x = String((a && a.term) || ""), y = String((b && b.term) || "");
  const pair = [...x].length === 1 && [...y].length === 1
    ? (areLookalike(x, y) ? { a: x, b: y } : null)
    : termLookalike(x, y);
  return pair ? diffSentence(kanjiDiff(pair.a, pair.b), gloss) : null;
}
