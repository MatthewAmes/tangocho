// Render Kotoba Quest's art.
//
//   node tools/make-sprites.mjs
//
// The sources are tools/sprite-designs.mjs (creatures) and tools/world-art.mjs (maps and
// people). This writes art/*.png for looking at, plus the two modules the game imports:
// src/data/quest-sprites.js and src/data/quest-world-art.js. Run it after changing any
// design — tools/test-sprites.mjs fails if you forget.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SPECIES, REGIONS } from "../src/data/quest-world.js";
import { CAST, PEOPLE } from "../src/data/quest-story.js";
import { draw } from "./sprite-designs.mjs";
import { sheet } from "./pixel-art.mjs";
import { paintMap, hero, guardianWalker, portrait, objects } from "./world-art.mjs";
import { encodePng } from "./png.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "art", "sprites");
const SPRITES_MODULE = path.join(ROOT, "src", "data", "quest-sprites.js");
const WORLD_MODULE = path.join(ROOT, "src", "data", "quest-world-art.js");
const uri = (img) => "data:image/png;base64," + encodePng(img).toString("base64");

/* Only regions with a written chapter ship their map; the rest wait for their story. */
const PLAYABLE = REGIONS.slice(0, 1);

fs.mkdirSync(OUT, { recursive: true });
const ids = Object.keys(SPECIES);
const images = ids.map(draw);
images.forEach((img, i) => fs.writeFileSync(path.join(OUT, ids[i] + ".png"), encodePng(img)));
fs.writeFileSync(path.join(ROOT, "art", "sprite-sheet.png"), encodePng(sheet(images, { scale: 4, cols: 5, bg: [32, 34, 46] })));
fs.writeFileSync(SPRITES_MODULE, `/* Generated by tools/make-sprites.mjs from tools/sprite-designs.mjs — do not edit by hand.
   Kotoba Quest's creatures, ${images[0].width}×${images[0].height} pixel art, shown at whole-number
   scales so every pixel stays square. A creature missing here falls back to its emoji. */
export const SPRITES = {
${ids.map((id, i) => `  ${id}: "${uri(images[i])}",`).join("\n")}
};
`);

const faces = Object.values(CAST).map((c) => c.portrait).filter(Boolean);
const walkers = PEOPLE.map((p) => p.walker).filter(Boolean);
const guardians = PLAYABLE.map((r) => r.guardian.look);
const walking = [...new Set([...walkers, ...guardians])];
const h = hero(), obj = objects();
const list = (o) => Object.entries(o).map(([k, v]) => `  ${k}: "${v}",`).join("\n");
const obfn = (arr, fn) => Object.fromEntries(arr.map((k) => [k, uri(fn(k))]));
const maps = PLAYABLE.map((r) => [r.theme, paintMap(r)]);
fs.writeFileSync(WORLD_MODULE, `/* Generated by tools/make-sprites.mjs from tools/world-art.mjs — do not edit by hand. */
export const MAPS = {
${list(Object.fromEntries(maps.map(([k, img]) => [k, uri(img)])))}
};
export const HERO = {
  down: ["${uri(h.down[0])}", "${uri(h.down[1])}"],
  up: ["${uri(h.up[0])}", "${uri(h.up[1])}"],
  right: ["${uri(h.right[0])}", "${uri(h.right[1])}"],
};
export const WALKERS = {
${list(obfn(walking, guardianWalker))}
};
export const PORTRAITS = {
${list(obfn(faces, portrait))}
};
export const OBJECTS = {
${list(Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, uri(v)])))}
};
`);
for (const [k, img] of maps) fs.writeFileSync(path.join(ROOT, "art", "map-" + k + ".png"), encodePng(sheet([img], { scale: 2, cols: 1, gap: 0 })));
fs.writeFileSync(path.join(ROOT, "art", "people-sheet.png"), encodePng(sheet(faces.map(portrait), { scale: 4, cols: 5, bg: [32, 34, 46] })));
const kb = (p) => Math.round(fs.statSync(p).size / 1024);
console.log(`${ids.length} creatures ${kb(SPRITES_MODULE)} KB, world ${kb(WORLD_MODULE)} KB`);
