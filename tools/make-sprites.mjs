// Render Kotoba Quest's creatures from their designs.
//
//   node tools/make-sprites.mjs
//
// tools/sprite-designs.mjs is the source; this writes art/sprites/<id>.png for looking at,
// art/sprite-sheet.png with all of them together, and src/data/quest-sprites.js, which the
// game imports. Run it after changing a design — tools/test-sprites.mjs fails if you forget.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SPECIES } from "../src/data/quest-world.js";
import { draw } from "./sprite-designs.mjs";
import { sheet } from "./pixel-art.mjs";
import { encodePng } from "./png.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "art", "sprites");
const MODULE = path.join(ROOT, "src", "data", "quest-sprites.js");

fs.mkdirSync(OUT, { recursive: true });
const ids = Object.keys(SPECIES);
const images = ids.map(draw);
const lines = ids.map((id, i) => {
  const png = encodePng(images[i]);
  fs.writeFileSync(path.join(OUT, id + ".png"), png);
  return `  ${id}: "data:image/png;base64,${png.toString("base64")}",`;
});
fs.writeFileSync(path.join(ROOT, "art", "sprite-sheet.png"), encodePng(sheet(images, { scale: 4, cols: 5, bg: [32, 34, 46] })));
fs.writeFileSync(MODULE, `/* Generated by tools/make-sprites.mjs from tools/sprite-designs.mjs — do not edit by hand.
   Kotoba Quest's creatures, ${images[0].width}×${images[0].height} pixel art, shown at whole-number
   scales so every pixel stays square. A creature missing here falls back to its emoji. */
export const SPRITES = {
${lines.join("\n")}
};
`);
console.log(`${ids.length} sprites, ${Math.round(fs.statSync(MODULE).size / 1024)} KB in ${path.relative(ROOT, MODULE)}`);
